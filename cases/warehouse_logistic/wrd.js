function para(text, opts = {}) {
    return new Paragraph({
        spacing: { before: 80, after: 80 },
        children: [new TextRun({ text, size: 22, font: "Arial", ...opts })]
    });
}
function bullet(text, boldPrefix = null) {
    const ch = [];
    if (boldPrefix) ch.push(new TextRun({ text: boldPrefix + " ", size: 22, font: "Arial", bold: true }));
    ch.push(new TextRun({ text, size: 22, font: "Arial" }));
    return new Paragraph({ numbering: { reference: "bullets", level: 0 }, spacing: { before: 60, after: 60 }, children: ch });
}
function bullet2(text) {
    return new Paragraph({ numbering: { reference: "bullets2", level: 0 }, spacing: { before: 40, after: 40 }, children: [new TextRun({ text, size: 22, font: "Arial" })] });
}
function numbered(text, boldPrefix = null) {
    const ch = [];
    if (boldPrefix) ch.push(new TextRun({ text: boldPrefix + " ", size: 22, font: "Arial", bold: true }));
    ch.push(new TextRun({ text, size: 22, font: "Arial" }));
    return new Paragraph({ numbering: { reference: "numbers", level: 0 }, spacing: { before: 60, after: 60 }, children: ch });
}
function spacer() { return new Paragraph({ children: [new TextRun("")], spacing: { before: 60, after: 60 } }); }
function divider() {
    return new Paragraph({
        border: { bottom: { style: BorderStyle.SINGLE, size: 6, color: "2E5DA8", space: 1 } },
        spacing: { before: 160, after: 160 }, children: []
    });
}
function highlight(text, fill = "EBF3FB") {
    return new Paragraph({
        spacing: { before: 120, after: 120 },
        indent: { left: 360, right: 360 },
        shading: { fill, type: ShadingType.CLEAR },
        children: [new TextRun({ text, size: 22, font: "Arial", italics: true })]
    });
}
function highlightBold(text, fill = "FFF3CD") {
    return new Paragraph({
        spacing: { before: 120, after: 120 },
        indent: { left: 360, right: 360 },
        shading: { fill, type: ShadingType.CLEAR },
        children: [new TextRun({ text, size: 22, font: "Arial", bold: true })]
    });
}
function makeTable(headers, rows, colWidths) {
    const total = colWidths.reduce((a, b) => a + b, 0);
    return new Table({
        width: { size: total, type: WidthType.DXA },
        columnWidths: colWidths,
        rows: [
            new TableRow({
                tableHeader: true,
                children: headers.map((h, i) => new TableCell({
                    borders, width: { size: colWidths[i], type: WidthType.DXA },
                    shading: { fill: "1F3864", type: ShadingType.CLEAR },
                    margins: { top: 100, bottom: 100, left: 150, right: 150 },
                    verticalAlign: VerticalAlign.CENTER,
                    children: [new Paragraph({ alignment: AlignmentType.CENTER, children: [new TextRun({ text: h, bold: true, size: 20, font: "Arial", color: "FFFFFF" })] })]
                }))
            }),
            ...rows.map((row, ri) => new TableRow({
                children: row.map((cell, ci) => new TableCell({
                    borders, width: { size: colWidths[ci], type: WidthType.DXA },
                    shading: { fill: ri % 2 === 0 ? "F5F9FF" : "FFFFFF", type: ShadingType.CLEAR },
                    margins: { top: 80, bottom: 80, left: 150, right: 150 },
                    verticalAlign: VerticalAlign.CENTER,
                    children: [new Paragraph({ children: [new TextRun({ text: cell, size: 20, font: "Arial" })] })]
                }))
            }))
        ]
    });
}

